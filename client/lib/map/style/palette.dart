/// 실내 도면 폴리곤의 색. 실내 화면과 야외 지도의 실내 오버레이가 함께 쓴다.
///
/// 규칙은 **걸을 수 있는 곳은 밝게, 막힌 곳은 어둡게** — 통로(footprint)가 가장
/// 밝고 매장이 한 단계 어둡다. 밝기로 못 가르는 자리(못 걷는 면)는 **색조로**
/// 가른다. 구분은 면이 아니라 **경계선이 만든다.**
///
/// 원본 SVG와 일치하지 않으며 의도적이다. 그 사정과 색조를 따뜻하게 유지하는
/// 이유는 `docs/client/map-style-rules.md`.
library;

/// 건물 바닥. 걸어 다니는 공간이라 가장 밝게 둔다.
const mapFootprintFill = '#FFFFFF';

/// 통로 외곽선. 검정 반투명은 iOS MapLibre에서 예상보다 진하게 합성돼 도면을
/// 격자처럼 보이게 했으므로 따뜻한 회색으로 낮춘다.
const mapFootprintOutline = '#C8C1B8';

/// 매장 폴리곤 면. 경계선이 얹힐 바탕을 주는 정도로만 낮춘다.
const mapStoreFill = '#F1EEEA';

/// 걸을 수 없는 면(아트리움 보이드·지하 기둥·조경) 면.
///
/// **매장과는 밝기가 아니라 색조로 갈린다.** 예전 `#F4F1ED`는 매장(`#F1EEEA`)과
/// 같은 웜 베이지에 3/255 밝은 값이라, 나란히 두면 사실상 같은 색이었다. 이제
/// 쿨 그레이(색상각 220°)로 빼서 매장의 웜(34°) 반대편에 둔다 — 같은 밝기
/// 대역에 있어도 두 면이 다른 것으로 읽힌다.
///
/// **어둡게 하지 않은 이유**는 밝기 위계가 이미 뜻을 갖기 때문이다. 통로
/// (`mapFootprintFill`)와 매장(`mapStoreFill`) **사이**를 지킨다 — 매장보다
/// 어두워지면 "밝을수록 걷는 곳"이 뒤집히고, 더현대 1F처럼 보이드가 큰 층에서는
/// **빈 공간이 화면의 주인공**이 된다. 실측표는 `docs/client/map-style-rules.md`.
const mapNonWalkableFill = '#EFF0F2';

/// 못 걷는 면 경계선. 면은 통로·매장과 밝기가 가까우므로 **이 선이 구분을
/// 거든다**(파일 상단 규칙). 매장 경계선(`mapStoreOutline`)보다 옅게 둬서 매장이
/// 계속 더 강하게 읽히게 한다 — 배경이 매장보다 또렷하면 안 된다.
///
/// 밝기는 통로 경계선과 같은 자리다. 옛 `#E4DFD8`은 면 대비가 거의 없는 위에
/// 선까지 옅어, 복도 한가운데 뚫린 보이드가 "복도가 조금 밝은 자리"로만 보였다.
/// 색조만 면과 같은 쿨 그레이로 맞춰 면·선이 한 덩어리로 읽히게 한다.
const mapNonWalkableOutline = '#C0C4C8';

/// 매장 경계선. 도면에서 실제로 구분을 만드는 값이라 면과 명도를 크게 벌린다.
///
/// `fillOutlineColor`는 **두께가 1px 고정**이라, 색으로 모자랄 때만 line 레이어를
/// 따로 얹는 비용을 낸다.
const mapStoreOutline = '#A69C90';

/// 고른 매장 폴리곤을 덮는 면의 불투명도.
///
/// **선택 칠은 매장명 라벨 위에 얹힌다**(레이어 순서가 그렇다). 0.16은 사실상
/// 안 보였고 0.35는 이름을 먹기 시작했다(실기기 확인). 색이 파랑에서 대분류
/// 색으로 바뀌면서 0.28에서 한 번 더 내렸다 — 어느 매장을 골랐는지는
/// [mapSelectionLineWidth]짜리 진한 테두리가 못 박고, 면은 범위만 말한다.
/// 테두리는 폴리곤 가장자리라 아무리 진해도 이름을 가리지 않는다.
const mapSelectionFillOpacity = 0.2;

/// 고른 매장 테두리의 굵기(px). 면을 줄인 만큼 여기서 받는다.
const mapSelectionLineWidth = 3.0;

/// 대분류가 없는 매장을 골랐을 때의 잉크.
///
/// 색은 [storeSelectionColorExpression]이 대분류마다 고르는데, 표에 없으면
/// 여기로 떨어진다. **기본 매장 색으로 떨어뜨리면 안 된다** — 골랐는데 아무
/// 일도 안 일어난 것처럼 보인다.
const mapSelectionFallback = '#5B5B5B';
