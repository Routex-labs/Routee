/// 실내 오버레이를 **켜고 끈 것이 무엇인지.**
///
/// 한동안 진단 파일에만 적히는 문자열이었다. 값이 필요했던 이유는
/// `_indoorEntered` 하나가 **두 가지 뜻을 겸하기** 때문이다 — "도면을 보고 있다"
/// 와 "건물 안에 있다". 파일에서 그 둘을 가리려고 출처를 함께 적었다.
///
/// 지금은 화면 동작도 이 값으로 갈린다([isViewingOnly]). 문자열 대신 열거형인
/// 이유가 그것이다 — 오타 하나가 "밖에 선 사람에게 실내 마커를 그린다"로
/// 조용히 되돌아가면 안 된다.
library;

enum IndoorEntrySource {
  /// 확대만으로 도면이 열렸다. 카메라가 임계 배율을 넘은 것이 전부라,
  /// 이 사람은 대개 아직 건물 밖에 서 있다.
  cameraZoom,

  /// 건물 정보 시트의 "실내 지도 보기". 역시 화면 조작이다.
  sheetTap,

  /// 안내 카드의 "OO(으)로 진입" — GPS가 문 앞이라고 말했고 사용자가 눌렀다.
  /// 걸어 들어온 것이다.
  guidance,

  /// 앱을 건물 안에서 켰다(GPS 콜드스타트).
  gpsColdStart,

  /// 건물 밖을 탭해 도면을 접었다.
  outsideTap,

  /// 그 밖 — 하단 바 "위치 지정", '홈'으로 나가기, 테스트 진입점.
  other;

  /// 이 진입이 **도면만 편 것**인지. 참이면 위치의 주인은 아직 GPS다.
  ///
  /// 밖에 선 사람에게 실내 마커를 그리면 그릴 근거가 GPS 좌표뿐이라, 흐린 점이
  /// 도면 위 엉뚱한 자리에 뜨고 사용자는 자기가 건물 안에 있다고 읽는다.
  /// 그 자리는 야외 GPS 마커가 그대로 지킨다.
  ///
  /// **"위치 지정"([other])은 여기 들어오지 않는다.** 그건 "내가 여기 있다"고
  /// 사람이 직접 말하는 조작이다.
  bool get isViewingOnly => this == cameraZoom || this == sheetTap;
}
